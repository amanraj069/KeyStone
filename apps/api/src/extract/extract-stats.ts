import { writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import type { GraphService } from '../graph/graph.service';
import { costUsd } from '../llm/pricing';
import type { ExtractedItem, ExtractSummary } from './extract.service';
import { MIN_DECISION_CONFIDENCE, MIN_SYSTEM_RELEVANCE } from './extract.schema';
import { ALIAS_FILE, nameKey, normalizeName } from './names';
import * as Q from './queries/extract.queries';

/** Words that often trail a system name ("Redis cache", "auth service") and are ignored when grouping spellings. */
const TRAILING_WORDS = /\b(service|services|cache|cluster|db|database|server|api|app|platform|pipeline|pipelines)\b/g;

/** Loose grouping key: lower case, no punctuation, no trailing generic words. */
function looseKey(name: string): string {
  return nameKey(name).replace(TRAILING_WORDS, '').replace(/[^a-z0-9]/g, '');
}

/**
 * Alias suggestions: raw names the LLM returned that collapse to the same loose
 * key but ended up as different canonical systems. A human decides (aliases.json).
 */
export function suggestAliases(summary: ExtractSummary): { canonical: string; variants: string[]; docs: number }[] {
  const canon = summary.canonicalizer;
  if (!canon) return [];
  const groups = new Map<string, Map<string, number>>();
  for (const [raw, docs] of summary.rawSystemNames) {
    const target = canon.canonical(raw);
    const key = looseKey(raw);
    if (!target || key.length < 2) continue;
    const group = groups.get(key) ?? new Map<string, number>();
    group.set(target, (group.get(target) ?? 0) + docs);
    groups.set(key, group);
  }
  const known = new Set(Object.keys(ALIAS_FILE.aliases).map(nameKey));
  return [...groups.values()]
    .filter((group) => group.size > 1)
    .map((group) => {
      const ranked = [...group.entries()].sort((a, b) => b[1] - a[1]);
      return {
        canonical: ranked[0][0],
        variants: ranked.slice(1).map(([name]) => name).filter((name) => !known.has(nameKey(name))),
        docs: ranked.reduce((sum, [, n]) => sum + n, 0),
      };
    })
    .filter((s) => s.variants.length > 0)
    .sort((a, b) => b.docs - a.docs);
}

/** Picks `count` items at random (for the quality check). */
function pickRandom<T>(items: T[], count: number): T[] {
  return [...items].sort(() => Math.random() - 0.5).slice(0, count);
}

function excerpt(text: string, max = 700): string {
  const flat = normalizeName(text).replace(/\s*\n\s*/g, ' / ');
  return flat.length > max ? `${flat.slice(0, max)}...` : flat;
}

/** One artifact next to what was extracted (and which items the score filters dropped). */
function exampleBlock({ item, value }: ExtractedItem): string[] {
  if (!value) return [];
  const systems = value.systems.map(
    (s) => `${s.name} (${s.relevance.toFixed(2)})${s.relevance < MIN_SYSTEM_RELEVANCE ? ' [dropped]' : ''}`,
  );
  return [
    `### ${item.id} (${item.label}, day ${item.day ?? '?'})`,
    '',
    `**Title:** ${item.title}`,
    '',
    `> ${excerpt(item.body)}`,
    '',
    `- **systems:** ${systems.join(', ') || '(none)'}`,
    ...value.decisions.map(
      (d) =>
        `- **decision** (${d.kind}, confidence ${d.confidence.toFixed(2)}${d.confidence < MIN_DECISION_CONFIDENCE ? ', dropped' : ''}; about ${d.systems.join(', ') || '-'}): ${d.summary}`,
    ),
    ...value.asserts.map((a) => `- **claim** (${a.system}): ${a.claim}${item.label === 'Page' ? '' : ' [not a Page: not kept]'}`),
    '',
  ];
}

/** Writes DATA_DIR/stats-extraction.md and returns its text. */
export async function writeExtractionStats(dataDir: string, graph: GraphService, summary: ExtractSummary): Promise<string> {
  const [counts] = await graph.roQuery<Record<string, number>>(summary.graph, Q.EXTRACTION_COUNTS);
  const top = await graph.roQuery<{ system: string; mentions: number }>(summary.graph, Q.TOP_SYSTEMS_BY_MENTIONS);
  const kinds = await graph.roQuery<{ kind: string; n: number }>(summary.graph, Q.DECISIONS_BY_KIND);
  const [noSystem] = await graph.roQuery<{ n: number }>(summary.graph, Q.DECISIONS_WITHOUT_SYSTEM);
  const stale = await graph.roQuery<{ page: string; title: string; decision: string; summary: string }>(summary.graph, Q.STALE_PAGES);

  const ok = summary.extracted.filter((e) => e.value);
  const cost = costUsd(summary.model, summary.tokens);
  const usd = (value: number | null) => (value === null ? 'n/a' : `$${value.toFixed(4)}`);
  const suggestions = suggestAliases(summary);
  const examples = pickRandom(
    ok.filter((e) => e.value!.systems.length + e.value!.decisions.length > 0),
    5,
  );

  const lines = [
    '# Extraction stats',
    '',
    `Generated by \`ExtractService\` on graph \`${summary.graph}\`; prompt \`${summary.promptVersion}\`; ` +
      `provider ${summary.provider}, model ${summary.model}.`,
    '',
    '## Artifacts',
    '',
    `- Candidates (Page, Thread, PR, Email, Ticket, Meeting): **${summary.candidates}**`,
    `- Selected (body over the minimum length): **${summary.selected}**`,
    `- Processed: **${ok.length}** (failed: ${summary.failures.length})`,
    `- Answered from cache: **${summary.fromCache}**; real LLM calls for extraction: **${summary.llmCalls}**`,
    `- Second pass: **${summary.linkSystems}** systems linked with **${summary.linkCalls}** real LLM calls; ` +
      `${summary.rejectedLinks} invalid links rejected`,
    `- Tokens: ${summary.tokens.inputTokens} in (${summary.tokens.cachedInputTokens} cached), ` +
      `${summary.tokens.outputTokens} out (${summary.tokens.reasoningTokens} reasoning); cost **${usd(cost)}**`,
    `- Seed vocabulary: ${summary.vocabulary.length} names`,
    '',
    '## Graph',
    '',
    '| Systems | MENTIONS | Decisions | superseded | SUPERSEDES | ASSERTS | Decisions without a system |',
    '| ---: | ---: | ---: | ---: | ---: | ---: | ---: |',
    `| ${counts?.systems ?? 0} | ${counts?.mentions ?? 0} | ${counts?.decisions ?? 0} | ${counts?.superseded ?? 0} | ` +
      `${counts?.supersedes ?? 0} | ${counts?.asserts ?? 0} | ${noSystem?.n ?? 0} |`,
    '',
    `Decisions by kind: ${kinds.map((k) => `${k.kind} ${k.n}`).join(', ') || 'none'}.`,
    '',
    '## Top 20 systems by mention count',
    '',
    '| # | System | Artifacts mentioning it |',
    '| ---: | --- | ---: |',
    ...top.map((row, i) => `| ${i + 1} | ${row.system} | ${row.mentions} |`),
    '',
    `## Stale pages (assert a superseded decision): ${stale.length}`,
    '',
    ...stale.map((s) => `- ${s.page} "${s.title}" asserts ${s.decision}: ${s.summary}`),
    '',
    '## Suggested aliases (review, then add to apps/api/src/extract/aliases.json)',
    '',
    ...(suggestions.length
      ? suggestions.slice(0, 40).map((s) => `- \`${s.variants.join('`, `')}\` -> \`${s.canonical}\` (${s.docs} mentions)`)
      : ['(none)']),
    '',
    '## 5 random extracted artifacts',
    '',
    ...examples.flatMap(exampleBlock),
    ...(summary.failures.length
      ? ['## Failures', '', ...summary.failures.slice(0, 30).map((f) => `- ${f.id}: ${f.error}`), '']
      : []),
  ];
  const text = lines.join('\n');
  await writeFile(join(dataDir, 'stats-extraction.md'), text, 'utf8');
  return text;
}
